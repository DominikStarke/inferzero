# Writes src/arc_switches.h: every ARC_* name a program here reads, so serverz's start line can mark a switch set in
# the environment that nothing reads (a mistyped name for ARC_XRAM_GB went unnoticed, PR #100, 2026-11-28; no typo is
# written here, since this file's names count as read).
# The names: each quoted "ARC_..." in the C++ sources (zero/, tools/, src/: getenv and the helpers that take a name),
# every name in scripts/options.tsv, and every ARC_ name in the PowerShell and bash scripts (bench/, scripts/, tests/,
# the launchers), which set or read some the C++ never does.
#   powershell -File scripts\gen-switch-list.ps1          write it
#   powershell -File scripts\gen-switch-list.ps1 -Check   exit 1 when the file is not what it would write (tests)
param([switch]$Check)
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$names = New-Object 'System.Collections.Generic.SortedSet[string]' ([StringComparer]::Ordinal)
$cpp = Get-ChildItem -Path (Join-Path $root "zero"), (Join-Path $root "tools"), (Join-Path $root "src") -Recurse -Include *.h, *.cpp |
  Where-Object { $_.Name -ne "arc_switches.h" }
foreach ($f in $cpp) {
  foreach ($m in [regex]::Matches([IO.File]::ReadAllText($f.FullName), '"(ARC_[A-Z0-9_]+)"')) { [void]$names.Add($m.Groups[1].Value) }
}
$scripts = @(Get-ChildItem -Path (Join-Path $root "bench"), (Join-Path $root "scripts"), (Join-Path $root "tests") -Recurse -Include *.ps1, *.sh, *.tsv) +
  @(Get-ChildItem -Path $root -File -Include *.ps1, *.sh -ErrorAction SilentlyContinue | Where-Object { $_.DirectoryName -eq $root })
foreach ($f in $scripts) {
  foreach ($m in [regex]::Matches([IO.File]::ReadAllText($f.FullName), '\b(ARC_[A-Z0-9_]+)\b')) { [void]$names.Add($m.Groups[1].Value) }
}
$sb = New-Object Text.StringBuilder
[void]$sb.Append("// Generated by scripts/gen-switch-list.ps1: every ARC_* name a program here reads (do not edit; run it again after`n")
[void]$sb.Append("// adding a switch, tests/test_switch_list.ps1 checks it is current). serverz's start line marks a name set that`n")
[void]$sb.Append("// is not here (tools/server_startup.h).`n")
[void]$sb.Append("#pragma once`n#include <string_view>`n`n")
[void]$sb.Append("inline constexpr std::string_view kArcSwitches[] = {`n")
foreach ($n in $names) { [void]$sb.Append("    `"$n`",`n") }
[void]$sb.Append("};`n")
$text = $sb.ToString()
$out = Join-Path $root "src\arc_switches.h"
if ($Check) {
  $have = if (Test-Path $out) { [IO.File]::ReadAllText($out) } else { "" }
  if ($have -ne $text) { Write-Host "src/arc_switches.h is not current: run scripts\gen-switch-list.ps1"; exit 1 }
  Write-Host "src/arc_switches.h is current ($($names.Count) names)"
  exit 0
}
[IO.File]::WriteAllText($out, $text, (New-Object Text.UTF8Encoding $false))
Write-Host "wrote src/arc_switches.h: $($names.Count) names"
